const READING = fs.existsSync('scripts/refs/holdout-reading.md') ? fs.readFileSync('scripts/refs/holdout-reading.md', 'utf8') : '';

async function sheet(out) {
  const esc = s => String(s ?? '').replace(/[&<>]/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' })[ch]);
  const cards = [];
  for (const { c, runs } of out) {
    let refImg = '';
    const pdf = path.join(LIB, c.page.file), png = path.resolve(OUT, c.id + '-ref.png');
    if (fs.existsSync(pdf) && !fs.existsSync(png)) spawnSync(PY, ['-I', 'scripts/refs/render-page.py', pdf, String(c.page.page), png, '1100'], { stdio: 'ignore' });
    if (fs.existsSync(png)) refImg = '<img src="' + pathToFileURL(png).href + '">';
    const plans = runs.filter(r => r.elements).map(r => { let svg; try { svg = planSVG({ ...r.plan, elements: r.elements, program: r.program }, { px: 520, pad: 18 }).svg; } catch (e) { svg = 'drawing failed: ' + esc(e.message); }
      return '<div class="p"><div class="h">' + esc(r.ask) + '</div><div class="' + (r.status === 'pass' ? 'ok' : 'f') + '">' + esc(r.status + ' · ' + r.units + ' units · parking ' + r.parking + '/' + r.required + ' · ' + r.buildings + ' bldg · cov ' + r.coverage + '%') + '</div>' + svg + '</div>'; });
    cards.push('<div class="c"><div class="t">' + esc(c.id + ' ' + c.R.name + ' — reference: ' + c.ref.units + ' units, parking ' + (c.ref.parking ?? '—') + ', ' + c.ref.acres + ' ac, ' + c.ref.form) + '</div><div class="row"><div class="r">' + (refImg || '<p>reference sheet not available (library or PyMuPDF missing)</p>') + '</div>' + plans.join('') + '</div></div>');
  }
  const html = '<!doctype html><meta charset="utf-8"><style>body{margin:0;font:11px Arial;width:2400px}.c{border:1px solid #ccc;margin:8px;padding:6px}.t{font-weight:bold;font-size:13px;margin-bottom:4px}.row{display:flex;gap:8px;align-items:flex-start}.r img{width:560px}.p{width:540px}.p svg{width:540px;height:auto}.h{font-weight:bold}.ok{color:#060}.f{color:#b00}</style>' + cards.join('');
  fs.writeFileSync(path.join(OUT, 'sheet.html'), html);
  const puppeteer = (await import('puppeteer-core')).default, exe = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
  const b = await puppeteer.launch({ executablePath: exe, headless: true, args: ['--no-sandbox', '--allow-file-access-from-files'] }), pg = await b.newPage(); await pg.setViewport({ width: 2400, height: 1200 });
  await pg.goto(pathToFileURL(path.resolve(OUT, 'sheet.html')).href, { waitUntil: 'load' }); await pg.screenshot({ path: path.join(OUT, 'sheet.png'), fullPage: true }); await b.close();
  console.log('sheet', path.resolve(OUT, 'sheet.png'));
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
