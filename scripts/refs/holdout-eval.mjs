// The layout engine against the reviewed HOLDOUT reference projects (scripts/refs/holdout-cases.mjs): each project's site
// reconstructed, its program asked for in words, the run's top option compared with what was actually designed (units,
// parking, buildings, footprint, coverage, density, form). Evaluation only: nothing here changes the engine or its
// templates (holdout values never drive generation; see docs/REFERENCE-PROVENANCE.md).
//   node scripts/refs/holdout-eval.mjs [--out build/holdout-eval] [--only P35] [--png] [--lib <reference library>]
// Writes <out>/eval.json, docs/bench/holdout-eval.md (unless --only), and with --png <out>/sheet.png: the engine's plan
// beside the reference sheet (rendered from the library with scripts/refs/render-page.py when the library and PyMuPDF
// are there; the library stays outside Git, so are the renders).
