// one case, one request: the brief from the words on the reconstructed site, with the project's own parking rule
export function evalRun(c, run) {
  const plan = { origin: [0, 0], ring: c.ring, front: c.front, streets: c.streets, setbacks: run.setbacks || { front: 25, side: 10, rear: 20, paving: 10 } };
  const brief = B.briefFromRequest(run.ask, plan);
  if (c.perUnit) brief.rules.values.parkingPerUnit = { v: c.perUnit.v, cls: 'verified', source: c.id + ': ' + c.perUnit.why };
  const t0 = Date.now(), rec = RUN.runBrief(brief), o = rec.options[0];
  if (!o) return { key: run.key, ask: run.ask, why: run.why, outcome: rec.outcome, problems: (rec.problems || []).map(p => p.msg), ms: Date.now() - t0 };
  const q = o.quantities, acres = c.ref.acres, siteSf = acres * 43560;
  const res = o.elements.filter(e => e.kind === 'building' && !e.future && e.use !== 'amenity');
  const allFoot = Object.values(q.byUse).reduce((t, u) => t + (u.footprint || 0), 0);
  const groups = new Set(res.map(e => e.court || e.wrap || e.id)).size;
  return { key: run.key, ask: run.ask, why: run.why, outcome: rec.outcome, status: o.validation.status, failed: o.validation.failed, name: o.name, ms: Date.now() - t0,
    units: q.totals.units, parking: q.parking.provided, required: q.parking.required, podium: q.parking.podium || 0, garage: q.parking.garage || 0,
    ratio: q.totals.units ? +(q.parking.provided / q.totals.units).toFixed(2) : null, buildings: groups, footprint: Math.round(allFoot), coverage: +(allFoot / siteSf * 100).toFixed(1),
    density: +(q.totals.units / acres).toFixed(1), elements: o.elements, program: o.program, plan };
}

const pct = (a, b) => a == null || b == null || !b ? '' : (a >= b ? '+' : '') + Math.round((a - b) / b * 100) + '%';
const cell = (eng, refv, fmt = x => x) => eng == null ? '—' : fmt(eng) + (refv != null && typeof refv === 'number' ? ' (' + pct(eng, refv) + ')' : '');

async function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const cases = CASES().filter(c => !ONLY || c.id === ONLY), out = [];
  for (const c of cases) {
    const runs = c.runs.map(r => evalRun(c, r));
    for (const r of runs) console.log(c.id.padEnd(5), r.key.padEnd(9), (r.outcome || '').padEnd(18), r.status || '', 'units', r.units, '/', c.ref.units, 'pk', r.parking, '/', c.ref.parking ?? '?', 'bldgs', r.buildings, '/', c.ref.buildings ?? '?', 'cov', r.coverage, '/', c.ref.coverage ?? '?', r.ms + 'ms', r.failed?.length ? 'fails ' + r.failed.join(',') : '');
    out.push({ c, runs });
  }
  fs.writeFileSync(path.join(OUT, 'eval.json'), JSON.stringify(out.map(({ c, runs }) => ({ id: c.id, how: c.how, ref: c.ref, perUnit: c.perUnit, runs: runs.map(({ elements, program, plan, ...r }) => r) })), null, 1));
  if (!ONLY) fs.writeFileSync('docs/bench/holdout-eval.md', markdown(out));
  if (PNG) await sheet(out);
}

function markdown(out) {
  const L = ['# Layout engine vs the holdout reference projects', '',
    'Generated by `node scripts/refs/holdout-eval.mjs` (engine ' + RUN.ENGINE_VERSION + '). Each holdout project’s site is reconstructed, its program asked',
    'for in words with the project’s own parking rule, and the run’s top option compared with what was designed. The reference values come',
    'from `data/reference/projects/<id>.json` (printed schedules and scaled measurements; see docs/REFERENCE-PROVENANCE.md). Percentages',
    'are engine vs reference. **Evaluation only:** these projects never drive the engine or its templates.', '',
    '| Project | Request | Outcome | Units | Parking (ratio) | Buildings | Footprint sf | Coverage | du/ac | Form |', '|---|---|---|---|---|---|---|---|---|---|'];
  for (const { c, runs } of out) {
    const R = c.ref; L.push('| **' + c.id + ' ' + c.R.name + '** (reference) | ' + R.acres + ' ac · ' + c.how.split(',')[0] + ' | as built | ' + R.units + ' | ' + (R.parking ?? '—') + (R.parking && R.units ? ' (' + (R.parking / R.units).toFixed(2) + ')' : '') + (R.required ? ', ' + R.required + ' required' : '') + ' | ' + (R.buildings ?? '—') + ' | ' + (R.footprint?.toLocaleString('en-US') ?? '—') + ' | ' + (R.coverage != null ? R.coverage + '%' : '—') + ' | ' + R.density + ' | ' + R.form + ', ' + R.floors + ' fl, ' + R.parkingType + ' |');
    for (const r of runs) L.push('| | ' + r.ask + ' | ' + (r.outcome || '') + (r.status ? ' · ' + r.status : '') + (r.failed?.length ? ' (' + r.failed.join(', ') + ')' : '') + ' | ' + cell(r.units, R.units) + ' | ' + (r.parking == null ? '—' : r.parking + ' (' + r.ratio + ')' + (r.podium ? ', ' + r.podium + ' podium' : '') + (r.garage ? ', ' + r.garage + ' garage' : '') + ', ' + r.required + ' required') + ' | ' + cell(r.buildings, R.buildings) + ' | ' + cell(r.footprint, R.footprint, x => x.toLocaleString('en-US')) + ' | ' + cell(r.coverage, R.coverage, x => x + '%') + ' | ' + cell(r.density, R.density) + ' | ' + (r.name || (r.problems || []).join('; ')) + ' |');
  }
  L.push('', '## Sites', '');
  for (const { c } of out) L.push('- **' + c.id + ':** ' + c.how + '. Parking rule: ' + (c.perUnit ? c.perUnit.v + ' a unit (' + c.perUnit.why + ')' : 'engine default') + '.');
  L.push('', READING, '');
  return L.join('\n') + '\n';
}

